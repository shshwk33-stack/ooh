"""Generate a reproducible SYNTHETIC CSV fixture inside the existing Mapo boundary.

This is a schema/quality-test fixture, not a delivery-route or advertising model.
"""
from __future__ import annotations
import argparse
import csv
from datetime import datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import random


def _inside(point, ring):
    x, y = point
    result = False
    for index, (ax, ay) in enumerate(ring):
        bx, by = ring[index - 1]
        if (ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
            result = not result
    return result


def generate(boundary_path, output_dir, seed=42):
    boundary_path, output_dir = Path(boundary_path), Path(output_dir)
    if output_dir.exists() and any(output_dir.iterdir()):
        raise ValueError("Output directory must be empty")
    boundary = json.loads(boundary_path.read_text(encoding="utf-8"))
    matches = [feature for feature in boundary["features"] if feature["properties"]["code"] == "11140"]
    if len(matches) != 1 or matches[0]["geometry"]["type"] != "Polygon":
        raise ValueError("Expected one Mapo polygon (code 11140)")
    rings = matches[0]["geometry"]["coordinates"]
    output_dir.mkdir(parents=True, exist_ok=True)
    positions = output_dir / "mapo_synthetic_gps.csv"
    rng = random.Random(seed)
    zone = timezone(timedelta(hours=9))
    rows = []
    # These are conceptual paths in geographic space, not actual road geometries.
    anchors = [(126.9245, 37.5572), (126.9515, 37.5445)]
    for day in range(3):
        for number, (base_lon, base_lat) in enumerate(anchors, 1):
            for step in range(12):
                stamp = datetime(2024, 5, 1, 9 + number, tzinfo=zone) + timedelta(days=day, minutes=step)
                lon = base_lon + min(step, 7) * .00022 + rng.uniform(-.000015, .000015)
                lat = base_lat + min(step, 7) * .00009 + rng.uniform(-.000015, .000015)
                point = (lon, lat)
                if not _inside(point, rings[0]) or any(_inside(point, ring) for ring in rings[1:]):
                    raise ValueError("Generated conceptual coordinate lies outside Mapo boundary")
                rows.append({"vehicle_id": f"SYNTH-VEH-{number:02d}", "timestamp": stamp.isoformat(), "longitude": f"{lon:.10f}", "latitude": f"{lat:.10f}", "data_type": "SYNTHETIC"})
    with positions.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=("vehicle_id", "timestamp", "longitude", "latitude", "data_type"), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    metadata = {"schema_version": "1.0", "dataset_kind": "vehicle_positions", "source": {"kind": "SYNTHETIC", "name": "Mapo GPS input-validation fixture", "sha256": hashlib.sha256(positions.read_bytes()).hexdigest(), "timezone": "Asia/Seoul", "provenance": "Generated by pipeline.scenario; not observed delivery GPS; no real road map matching", "license": "Project-generated test fixture"}, "spatial": {"input_crs": "EPSG:4326", "coordinate_order": "longitude_latitude"}, "generator": {"seed": seed, "method": "Two conceptual point sequences, 3 arbitrarily selected days, 12 one-minute samples per vehicle/day, bounded random coordinate jitter; not a calibrated movement model", "version": "scenario-1.0.0", "boundary_sha256": hashlib.sha256(boundary_path.read_bytes()).hexdigest(), "boundary_reference_year": 2013, "dates_are_synthetic": True, "road_constrained": False, "observations": len(rows)}}
    (output_dir / "mapo_synthetic_gps.metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    return metadata


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--boundary", default="public/data/seoul-districts-2013.geojson")
    parser.add_argument("--output", required=True)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)
    metadata = generate(args.boundary, args.output, args.seed)
    print(json.dumps({"source_kind": "SYNTHETIC", "observations": metadata["generator"]["observations"], "seed": args.seed}))


if __name__ == "__main__":
    main()
